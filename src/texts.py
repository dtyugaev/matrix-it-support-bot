def t(key: str, **kwargs: Any) -> str:
    """Вернуть фразу по ключу с подстановкой параметров.

    :param key: ключ словаря :data:`TEXTS`.
    :param kwargs: значения для подстановки в шаблон.
    :raises KeyError: если ключ отсутствует (защита от опечаток в коде).
    """
    try:
        template = TEXTS[key]
    except KeyError as exc:  # pragma: no cover - защита от опечаток
        raise KeyError(f"Не найдена фраза с ключом '{key}' в src/texts.py") from exc
    if not kwargs:
        return template
    return template.format(**kwargs)
